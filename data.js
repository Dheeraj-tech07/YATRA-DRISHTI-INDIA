function getAllHeritagePlaces() {

    const places = [];

    Object.entries(INDIA_HERITAGE).forEach(
        ([state, data]) => {

            data.forEach((place, index) => {

                places.push({

                    state: state,

                    name: place[0],

                    category: place[1],

                    lat: place[2],

                    lng: place[3],

                    index: index

                });

            });

        }
    );

    return places;

}
